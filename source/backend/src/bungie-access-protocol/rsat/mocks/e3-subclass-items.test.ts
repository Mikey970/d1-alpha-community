import {afterEach,expect,it,vi} from 'vitest';
import native from './e3-abilities.native.json';
import registrations from './e3-subclass-items.native.json';
afterEach(()=>vi.unstubAllEnvs());
it.each(native.presets)('publishes preset $index as an owned, equipped native grid and switches back cleanly',async preset=>{
  vi.resetModules();
  vi.stubEnv('D1A_E3_ABILITY_PRESET',String(preset.index));
  vi.stubEnv('D1A_INVENTORY_PROBE_ITEM','1');
  vi.stubEnv('D1A_TALENT_PROBE','1');
  vi.stubEnv('D1A_EQUIPMENT_PROFILE','');
  vi.stubEnv('D1A_TALENT_STATE_PATH','');
  const kit=await import('./e3-subclass-items');
  const loadout=await import('./loadout');
  const values=await import('./values');
  const row=registrations.find(r=>r.preset===preset.index)!;
  const item=kit.e3SubclassItem()!;
  expect(loadout.equippedItemSoid(1)).toBe(item.soid);
  expect(loadout.inventoryWeapons().filter(i=>i.soid===item.soid)).toHaveLength(1);
  expect(loadout.inventoryWeapons().filter(i=>i.bucket===7).length).toBeLessThan(5);
  const gear=values.stubGearCf();
  expect(gear.unknown1.unknown0.map(a=>a.unknown0)).toEqual(preset.abilities.map(a=>a.index));
  expect(gear.unknown3.unknown0[1]).toMatchObject({soid:item.soid,defIndex:row.definition});
  const grid=values.stubInventoryItem(item.soid,item.defIndex,1).unknown4!;
  expect(grid.unknown0).toBe(row.grid);
  expect(grid.unknown4!.unknown0.filter(n=>n===1)).toHaveLength(row.nodes.length);
  expect(grid.unknown5!.unknown0.map(b=>row.nodes[b.unknown0!]!.ability)).toEqual(preset.abilities.map(a=>a.index));
  expect(kit.e3SubclassValue(item.soid,item.defIndex+1)).toBeUndefined();
  const original=loadout.inventoryWeapons().find(i=>i.slot===1 && i.defIndex===row.donorDefinition)!;
  expect(original).toBeDefined();
  expect(loadout.equipInventoryProbe(original.soid)).toBe(true);
  expect(kit.e3EquippedAbilities(loadout.equippedItemSoid(1))).toBeUndefined();
  const module=await import(row.donorDefinition===434?'./titan-arc-state':row.donorDefinition===438?'./hunter-ghost-state':row.donorDefinition===441?'./radiance-state':'./talent-state');
  expect(values.stubGearCf().unknown1.unknown0).toEqual(module.talentAbilityRecords());
  expect(loadout.equipInventoryProbe(item.soid)).toBe(true);
  expect(values.stubGearCf().unknown1.unknown0).toEqual(kit.e3EquippedAbilities(item.soid));
});
